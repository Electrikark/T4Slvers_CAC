#!/usr/bin/env node
/* Writes the practice messages and the scam guide of learn.html from data/scam-guide.js, so the
   page and the data can never say different things. Everything is plain HTML: every message,
   its answer and every scam open without JavaScript. js/learn.js only turns the practice into
   one message at a time with two choices.

     node scripts/build-learn.cjs          rewrite the block between the markers
     node scripts/build-learn.cjs --check  fail if learn.html differs from the data (npm test)

   Only the block between the two marker comments is generated. Everything else on the page
   (the four warning signs and the note for someone with no one to ask) is written by hand. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const ROOT = path.join(__dirname, '..');
const PAGE = path.join(ROOT, 'learn.html');
const DATA = path.join(ROOT, 'data/scam-guide.js');
const START = '<!-- learn-guide:start (generated by scripts/build-learn.cjs from data/scam-guide.js; do not edit by hand) -->';
const END = '<!-- learn-guide:end -->';
// The label on a step that no official page states directly: the project's own advice.
const OWN_ADVICE = 'Tech for Silvers advice';
const CHANNELS = { text: 'Text', email: 'Email', unknown: 'Not sure' };

const escape = text => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function loadGuide() {
  const sandbox = {};
  sandbox.window = sandbox;
  vm.runInNewContext(fs.readFileSync(DATA, 'utf8'), sandbox, { filename: DATA });
  return sandbox.TFS_GUIDE;
}

function credit(source, guide, where) {
  if (!source) return `<span class="help-source own-advice">${OWN_ADVICE}</span>`;
  const page = guide.sources[source];
  if (!page) throw new Error(where + ': unknown source ' + source);
  return `<a class="help-source" href="${escape(page.url)}">Source: ${escape(page.title)} ↗</a>`;
}

// The message with each word to notice wrapped, in order. Marks must not overlap.
function marked(item) {
  let html = '', at = 0;
  const found = item.marks.map(mark => {
    const start = item.text.indexOf(mark.words);
    if (start < 0) throw new Error(item.id + ': mark not in message: ' + mark.words);
    return { start, end: start + mark.words.length };
  }).sort((a, b) => a.start - b.start);
  for (const mark of found) {
    if (mark.start < at) throw new Error(item.id + ': marks overlap');
    html += escape(item.text.slice(at, mark.start)) + `<span class="practice-mark">${escape(item.text.slice(mark.start, mark.end))}</span>`;
    at = mark.end;
  }
  return html + escape(item.text.slice(at));
}

function practiceItem(item, n, total, guide, pad) {
  const lines = [`${pad}<li id="${escape(item.id)}" class="practice-item" data-scam="${item.scam}">`,
    `${pad}  <p class="practice-count">Message ${n} of ${total} · ${escape(item.from)}</p>`,
    `${pad}  <blockquote class="practice-message">${marked(item)}</blockquote>`,
    `${pad}  <div class="practice-choices" hidden>`,
    `${pad}    <button type="button" class="secondary" data-choice="pause" aria-pressed="false">I would pause</button>`,
    `${pad}    <button type="button" class="secondary" data-choice="ordinary" aria-pressed="false">It looks ordinary</button>`,
    `${pad}  </div>`,
    `${pad}  <p class="practice-feedback" tabindex="-1" hidden></p>`,
    `${pad}  <details class="practice-answer">`,
    `${pad}    <summary>What to notice</summary>`,
    `${pad}    <div class="detail-body">`,
    `${pad}      <p class="practice-verdict">${item.scam ? 'This one is a scam.' : 'This one looks ordinary.'}</p>`];
  if (item.marks.length) {
    lines.push(`${pad}      <ul class="practice-notes">`,
      ...item.marks.map(mark => `${pad}        <li><span class="practice-quote">“${escape(mark.words)}”</span> ${escape(mark.note)}</li>`),
      `${pad}      </ul>`);
  }
  lines.push(`${pad}      <p class="practice-do"><strong>What to do:</strong> ${escape(item.todo.text)} ${credit(item.todo.source, guide, item.id)}</p>`,
    `${pad}    </div>`,
    `${pad}  </details>`,
    `${pad}  <button type="button" class="primary practice-next" hidden>${n === total ? 'Finish' : 'Next message'}</button>`,
    `${pad}</li>`);
  return lines;
}

function practice(guide, pad) {
  const total = guide.practice.length;
  const lines = [`${pad}<section id="practice" class="practice-round" aria-labelledby="practice-title">`,
    `${pad}  <p class="eyebrow">PRACTICE AT YOUR OWN PACE</p>`,
    `${pad}  <h2 id="practice-title">Would you pause for this one?</h2>`,
    `${pad}  <p class="section-intro">Here are ${total} made-up messages. Some are scams and some are ordinary. Read each one and decide. There is no score, and nothing you choose is saved.</p>`,
    `${pad}  <ol class="practice-list">`];
  guide.practice.forEach((item, i) => lines.push(...practiceItem(item, i + 1, total, guide, pad + '    ')));
  lines.push(`${pad}  </ol>`,
    `${pad}  <div id="practice-done" class="practice-done" hidden>`,
    `${pad}    <h3 id="practice-done-title" tabindex="-1">You finished the practice.</h3>`,
    `${pad}    <p>Well done for taking the time. You can come back and practice again whenever you like.</p>`,
    `${pad}    <button type="button" id="practice-again" class="secondary">Start again</button>`,
    `${pad}  </div>`,
    `${pad}</section>`);
  return lines;
}

function scam(item, guide, pad) {
  for (const n of item.signs) if (!guide.signs[n]) throw new Error(item.id + ': unknown sign ' + n);
  const lines = [`${pad}<details id="scam-${escape(item.id)}" class="help-topic-card guide-card">`,
    `${pad}  <summary>${escape(item.title)}<span class="guide-hook">${escape(item.hook)}</span></summary>`,
    `${pad}  <div class="detail-body">`,
    `${pad}    <h3>What it can sound like</h3>`,
    `${pad}    <blockquote class="guide-example">“${escape(item.example.text)}”</blockquote>`,
    `${pad}    <p class="small-note">A made-up example.</p>`,
    `${pad}    <h3>Why it works</h3>`,
    `${pad}    <p>${escape(item.why)}</p>`,
    `${pad}    <h3>Warning signs it uses</h3>`,
    `${pad}    <ul class="guide-signs">`,
    ...item.signs.map(n => `${pad}      <li><a href="#sign-${n}">${n} · ${escape(guide.signs[n])}</a></li>`),
    `${pad}    </ul>`,
    `${pad}    <h3>What to do</h3>`,
    `${pad}    <ol class="help-steps">`,
    ...item.steps.map(step => `${pad}      <li>${escape(step.text)} ${credit(step.source, guide, item.id)}</li>`),
    `${pad}    </ol>`,
    `${pad}    <div class="guide-links">`,
    `${pad}      <a class="secondary button-link" href="check.html?example=${escape(item.id)}">Try this message in the checker<span class="sr-only">: ${escape(item.title)}</span></a>`,
    `${pad}      <p class="small-note">It loads into the checker. Choose ${CHANNELS[item.example.channel]}, then check it when you are ready.</p>`,
    `${pad}      <a class="guide-recover" href="recover.html#${escape(item.recover)}">If this already happened to you<span class="sr-only">: ${escape(item.title)}</span></a>`,
    `${pad}    </div>`,
    `${pad}  </div>`,
    `${pad}</details>`];
  if (!CHANNELS[item.example.channel]) throw new Error(item.id + ': unknown channel ' + item.example.channel);
  return lines;
}

function scams(guide, pad) {
  const lines = [`${pad}<section id="guide" class="scam-guide" aria-labelledby="guide-title">`,
    `${pad}  <p class="eyebrow">SCAM GUIDE</p>`,
    `${pad}  <h2 id="guide-title">Scam patterns, one at a time</h2>`,
    `${pad}  <p class="section-intro">Open a pattern to see an example and a protective step. Being fooled says nothing about you.</p>`];
  if (!guide.approvedBy) lines.push(`${pad}  <p id="guide-draft" class="help-draft">Draft: this guide and the practice notes are waiting for a person to check them against their sources.</p>`);
  lines.push(`${pad}  <div class="recovery-options guide-list">`);
  for (const item of guide.scams) lines.push(...scam(item, guide, pad + '    '));
  lines.push(`${pad}  </div>`, `${pad}</section>`);
  return lines;
}

function block(guide) {
  const pad = '    ';
  return [pad + START, ...practice(guide, pad), ...scams(guide, pad), pad + END].join('\n');
}

function render(page, guide) {
  const a = page.indexOf(START), b = page.indexOf(END);
  if (a < 0 || b < a) throw new Error('learn.html is missing the learn-guide markers');
  const lineStart = page.lastIndexOf('\n', a) + 1;
  return page.slice(0, lineStart) + block(guide) + page.slice(b + END.length);
}

function main() {
  const page = fs.readFileSync(PAGE, 'utf8');
  const next = render(page, loadGuide());
  if (process.argv.includes('--check')) {
    if (next !== page) {
      console.error('learn.html does not match data/scam-guide.js. Run: node scripts/build-learn.cjs');
      return 1;
    }
    console.log('Learn page matches data/scam-guide.js');
    return 0;
  }
  fs.writeFileSync(PAGE, next);
  console.log('Wrote the practice and the scam guide in learn.html from data/scam-guide.js');
  return 0;
}

if (require.main === module) process.exitCode = main();
module.exports = { render, loadGuide, block, START, END, OWN_ADVICE, CHANNELS };
