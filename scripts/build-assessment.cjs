// The browser artifact wraps the source verbatim; it contains no separate policy.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'src/assessment.js'), 'utf8');
const output = '// Generated by scripts/build-assessment.cjs. Edit src/assessment.js.\n' +
  '(function (root) {\nconst module = { exports: {} };\n' + source +
  '\nroot.TfsAssessment = module.exports;\n})(typeof window !== "undefined" ? window : globalThis);\n';
const target = path.join(root, 'js/assessment-gate.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
    console.error('Stale browser gate. Run node scripts/build-assessment.cjs.');
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(target, output);
}
