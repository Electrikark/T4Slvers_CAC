function inlineBlock(data, place, today) {
  const pad = place === 'paste' ? '            ' : '            ';
  const [start, end] = MARK('howto-' + place);
  const title = place === 'paste' ? 'Need help adding the message?' : 'Need help using a screenshot?';
  const link = place === 'paste' ? 'text-and-email' : 'screenshots';
  const guides = data.guides.filter(g => g.inline === place);
  if (!guides.length) throw new Error('No guides marked inline: ' + place);
  const lines = [pad + start, `${pad}<details id="help-${place}" class="howto-inline">`,
    `${pad}  <summary>${escape(title)}</summary>`, `${pad}  <div class="howto-inline-body">`,
    `${pad}    <p class="howto-inline-note">Your message stays in the box while you read this.</p>`];
  for (const guide of guides) {
    lines.push(`${pad}    <section class="howto-guide" aria-labelledby="inline-${guide.id}-title">`,
      `${pad}      <h3 id="inline-${guide.id}-title">${escape(guide.title)}</h3>`,
      ...guideBody(guide, data, pad + '      ', { prefix: 'inline-', today, full: false }),
      `${pad}    </section>`);
  }
  lines.push(`${pad}    <p class="howto-more"><a href="help.html#${link}">Open the full guide, with pictures and practice</a> <span>This leaves the page. Use your browser’s Back button to return.</span></p>`,
    `${pad}  </div>`, `${pad}</details>`, pad + end);
  return lines.join('\n');
}

function replaceBlock(page, name, block, file) {
  const [start, end] = MARK(name);
  const a = page.indexOf(start), b = page.indexOf(end);
  if (a < 0 || b < a) throw new Error(`${file} is missing the ${name} markers`);
  const lineStart = page.lastIndexOf('\n', a) + 1;
  return page.slice(0, lineStart) + block + page.slice(b + end.length);
}

function render({ help, check, data, today }) {
  checkLabels(data, check);
  let nextCheck = replaceBlock(check, 'howto-paste', inlineBlock(data, 'paste', today), 'check.html');
  nextCheck = replaceBlock(nextCheck, 'howto-screenshot', inlineBlock(data, 'screenshot', today), 'check.html');
  const nextHelp = replaceBlock(help, 'howto', helpBlock(data, today), 'help.html');
  return { help: nextHelp, check: nextCheck };
}

function main() {
  const today = new Date().toISOString().slice(0, 10);
  const help = fs.readFileSync(HELP, 'utf8');
  const check = fs.readFileSync(CHECK, 'utf8');
  let next;
  try {
    next = render({ help, check, data: load(), today });
  } catch (error) {
    console.error('How-to guides: ' + error.message);
    return 1;
  }
  if (process.argv.includes('--check')) {
    const stale = [next.help !== help && 'help.html', next.check !== check && 'check.html'].filter(Boolean);
    if (stale.length) {
      console.error(stale.join(' and ') + ' do not match data/how-to.js. Run: node scripts/build-howto.cjs');
      return 1;
    }
    console.log('How-to guides match data/how-to.js');
    return 0;
  }
  fs.writeFileSync(HELP, next.help);
  fs.writeFileSync(CHECK, next.check);
  console.log('Wrote the how-to guides in help.html and check.html from data/how-to.js');
  return 0;
}

if (require.main === module) process.exitCode = main();
module.exports = { load, render, checkProblem, checkLabels, counts, CHECK_FIELDS, MARK };
