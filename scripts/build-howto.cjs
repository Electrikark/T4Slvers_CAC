#!/usr/bin/env node
/* Writes the how-to guides into help.html and the help beside the message box in check.html,
   both from data/how-to.js, so the full guide and the short help can never disagree.

     node scripts/build-howto.cjs          rewrite the blocks between the markers
     node scripts/build-howto.cjs --check  fail if either page differs from the data (npm test)

   The build refuses, rather than writes, when:
   - a phone guide claims it was checked on a phone but the record is incomplete or made up
   - an app guide quotes a button or label that is not on check.html
   - a picture is named that does not exist on disk
   Everything is plain HTML: <details> opens without JavaScript, nothing moves on its own, and
   every step is visible at once once a device is chosen, so the reader sets the pace. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const ROOT = path.join(__dirname, '..');
const DATA = path.join(ROOT, 'data/how-to.js');
const HELP = path.join(ROOT, 'help.html');
const CHECK = path.join(ROOT, 'check.html');
const MARK = name => [`<!-- ${name}:start (generated by scripts/build-howto.cjs from data/how-to.js; do not edit by hand) -->`, `<!-- ${name}:end -->`];

// A device counts as checked only with all of these. `app` must name the guide's app, so a
// record cannot quietly describe a different app than the steps are written for.
const CHECK_FIELDS = ['by', 'on', 'phone', 'system', 'app'];
const PLACEHOLDER = /^(?:x+|tbd|todo|name|reviewer|reviewer_name|checker|someone|unknown|n\/?a|-+|\?+)$/i;

const escape = text => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function load(file = DATA) {
  const sandbox = {};
  sandbox.window = sandbox;
  vm.runInNewContext(fs.readFileSync(file, 'utf8'), sandbox, { filename: file });
  return sandbox.TFS_HOWTO;
}

function validDate(text, today) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(text)) return false;
  const date = new Date(text + 'T00:00:00Z');
  return !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === text && text <= today;
}

// Returns null when the record is a real, complete check, otherwise the reason it is not.
function checkProblem(device, today) {
  const record = device.checked;
  if (record === null || record === undefined) return 'not checked';
  if (typeof record !== 'object') return 'checked must be null or a record';
  for (const field of CHECK_FIELDS) {
    const value = record[field];
    if (typeof value !== 'string' || !value.trim()) return `missing ${field}`;
    if (PLACEHOLDER.test(value.trim()) || /placeholder|example/i.test(value)) return `${field} looks like a placeholder`;
  }
  if (!validDate(record.on, today)) return 'on must be a real date, YYYY-MM-DD, not in the future';
  if (!record.app.toLowerCase().includes(device.app.toLowerCase())) return `app must name ${device.app}`;
  return null;
}

const longDate = iso => new Date(iso + 'T00:00:00Z').toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric', timeZone: 'UTC' });

function pngSize(file) {
  const data = fs.readFileSync(file);
  if (data.toString('ascii', 1, 4) !== 'PNG') throw new Error(file + ' is not a PNG');
  return { width: data.readUInt32BE(16), height: data.readUInt32BE(20) };
}

function figure(data, key, pad) {
  const picture = data.pictures && data.pictures[key];
  if (!picture) throw new Error('Unknown picture ' + key);
  const file = path.join(ROOT, picture.file);
  if (!fs.existsSync(file)) throw new Error('Missing picture file ' + picture.file + ' (run node scripts/capture-howto.cjs)');
  const size = pngSize(file);
  // Pictures are shown at most half size so text in them matches the page's own text size.
  return `${pad}<figure class="howto-figure"><img src="${escape(picture.file)}" width="${Math.round(size.width / 2)}" height="${Math.round(size.height / 2)}" loading="lazy" alt="${escape(picture.alt)}"></figure>`;
}

function stepList(steps, data, pad, { pictures }) {
  const lines = [`${pad}<ol class="howto-steps">`];
  for (const step of steps) {
    if (pictures && step.picture) {
      lines.push(`${pad}  <li><p>${escape(step.text)}</p>`, figure(data, step.picture, pad + '    '), `${pad}  </li>`);
    } else {
      lines.push(`${pad}  <li>${escape(step.text)}</li>`);
    }
  }
  lines.push(`${pad}</ol>`);
  return lines;
}

function device(guideId, dev, data, pad, { prefix, today }) {
  const problem = checkProblem(dev, today);
  if (problem && problem !== 'not checked') throw new Error(`${guideId}/${dev.id}: ${problem}`);
  const checked = !problem;
  const lines = [`${pad}<details id="${prefix}${escape(guideId)}-${escape(dev.id)}" class="howto-device">`,
    `${pad}  <summary>${escape(dev.label)}<span class="howto-app">${escape(dev.app)}</span></summary>`,
    `${pad}  <div class="howto-device-body">`];
  // Pictures of a phone's own screens are only shown for a setup someone actually checked.
  lines.push(...stepList(dev.steps, data, pad + '    ', { pictures: checked }));
  lines.push(checked
    ? `${pad}    <p class="howto-checked">Checked on one ${escape(dev.checked.phone)}, ${escape(dev.checked.system)}, ${escape(dev.checked.app)}, on ${longDate(dev.checked.on)}. Other phones and versions may look different.</p>`
    : `${pad}    <p class="howto-unchecked">Not yet checked on a phone. Your screens may look different. If a step does not match, ask someone to help.</p>`);
  lines.push(`${pad}  </div>`, `${pad}</details>`);
  return lines;
}

function guideBody(guide, data, pad, options) {
  const lines = [];
  if (guide.safety) lines.push(`${pad}<p class="howto-safety"><strong>Careful:</strong> ${escape(guide.safety)}</p>`);
  if (guide.kind === 'phone') {
    lines.push(`${pad}<p class="howto-choose">Choose your phone.</p>`, `${pad}<div class="howto-devices">`);
    for (const dev of guide.devices) lines.push(...device(guide.id, dev, data, pad + '  ', options));
    lines.push(`${pad}</div>`);
  } else if (guide.kind === 'app') {
    if (guide.why && options.full) lines.push(`${pad}<p class="howto-why">${escape(guide.why)}</p>`);
    lines.push(...stepList(guide.steps, data, pad, { pictures: options.full }));
  } else {
    throw new Error(guide.id + ': unknown kind ' + guide.kind);
  }
  if (guide.tips && options.full) {
    lines.push(`${pad}<ul class="howto-tips">`, ...guide.tips.map(tip => `${pad}  <li>${escape(tip)}</li>`), `${pad}</ul>`);
  }
  return lines;
}

function checkLabels(data, checkHtml) {
  // Compare against the page's visible text, so a label inside an attribute or a comment
  // does not count as being on the screen. The generated help is removed first: it quotes the
  // labels itself, so leaving it in would let a guide vouch for a button that no longer exists.
  let page = checkHtml;
  for (const name of ['howto-paste', 'howto-screenshot']) {
    const [start, end] = MARK(name);
    const a = page.indexOf(start), b = page.indexOf(end);
    if (a >= 0 && b > a) page = page.slice(0, a) + page.slice(b + end.length);
  }
  const visible = page.replace(/<!--[\s\S]*?-->/g, ' ').replace(/<script[\s\S]*?<\/script>/g, ' ')
    .replace(/<[^>]+>/g, ' ').replace(/&amp;/g, '&').replace(/\s+/g, ' ');
  const missing = [];
  for (const guide of data.guides) {
    for (const label of guide.uiLabels || []) if (!visible.includes(label)) missing.push(`${guide.id}: "${label}"`);
  }
  if (missing.length) throw new Error('These labels are quoted in the guides but are not on check.html:\n  ' + missing.join('\n  '));
}

function counts(data, today) {
  let total = 0, checked = 0;
  const devices = [...data.guides.filter(g => g.kind === 'phone').flatMap(g => g.devices), ...(data.practice.screenshot.devices || [])];
  for (const dev of devices) { total++; if (!checkProblem(dev, today)) checked++; }
  return { total, checked };
}

function helpBlock(data, today) {
  const pad = '    ';
  const [start, end] = MARK('howto');
  const groups = [
    { id: 'text-and-email', title: 'Copy and paste a text or email', ids: ['copy-text', 'copy-email', 'paste'] },
    { id: 'screenshots', title: 'Use a screenshot', ids: ['take-screenshot', 'choose-screenshot', 'review-screenshot'] }
  ];
  const { total, checked } = counts(data, today);
  const lines = [pad + start];
  lines.push(`${pad}<nav class="page-jumps" aria-label="On this page">`,
    ...groups.map(g => `${pad}  <a href="#${g.id}">${escape(g.title)}</a>`),
    `${pad}  <a href="#practice">Practice</a>`, `${pad}</nav>`);
  lines.push(`${pad}<p id="howto-status" class="howto-status">${checked} of ${total} phone guides have been checked on a real phone so far. Guides that have not are marked.</p>`);
  for (const group of groups) {
    lines.push(`${pad}<section id="${group.id}" class="howto-group" aria-labelledby="${group.id}-title">`,
      `${pad}  <h2 id="${group.id}-title">${escape(group.title)}</h2>`);
    for (const id of group.ids) {
      const guide = data.guides.find(g => g.id === id);
      if (!guide) throw new Error('Unknown guide ' + id);
      lines.push(`${pad}  <section id="${guide.id}" class="howto-guide" aria-labelledby="${guide.id}-title">`,
        `${pad}    <h3 id="${guide.id}-title">${escape(guide.title)}</h3>`,
        `${pad}    <p class="howto-goal">${escape(guide.goal)}</p>`,
        ...guideBody(guide, data, pad + '    ', { prefix: '', today, full: true }),
        `${pad}  </section>`);
    }
    lines.push(`${pad}</section>`);
  }
  const listed = new Set(groups.flatMap(g => g.ids));
  const unlisted = data.guides.filter(g => !listed.has(g.id)).map(g => g.id);
  if (unlisted.length) throw new Error('Guides not placed on help.html: ' + unlisted.join(', '));
  lines.push(...practiceBlock(data, pad, today));
  lines.push(pad + end);
  return lines.join('\n');
}

