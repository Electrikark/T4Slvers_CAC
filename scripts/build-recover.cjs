#!/usr/bin/env node
/* Writes the "What happened?" topics of recover.html from data/help-cards.js, so the page and
   the data can never say different things. The topics are plain <details> elements: they open
   without JavaScript, several can stay open, and printing opens them all (js/site.js).

     node scripts/build-recover.cjs          rewrite the block between the markers
     node scripts/build-recover.cjs --check  fail if recover.html differs from the data (npm test)

   Only the block between the two marker comments is generated. Everything else on the page
   (the urgent payment box, the hotline, the plan for today, the recovery-offer warning) is
   written by hand. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const ROOT = path.join(__dirname, '..');
const PAGE = path.join(ROOT, 'recover.html');
const DATA = path.join(ROOT, 'data/help-cards.js');
const START = '<!-- help-cards:start (generated by scripts/build-recover.cjs from data/help-cards.js; do not edit by hand) -->';
const END = '<!-- help-cards:end -->';
// The label on a step that no official page states directly: the project's own advice.
const OWN_ADVICE = 'Tech for Silvers advice';

const escape = text => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function loadHelp() {
  const sandbox = {};
  sandbox.window = sandbox;
  vm.runInNewContext(fs.readFileSync(DATA, 'utf8'), sandbox, { filename: DATA });
  return sandbox.TFS_HELP;
}

function steps(card, help, pad) {
  const items = card.steps.map(step => {
    const source = step.source && help.sources[step.source];
    if (step.source && !source) throw new Error(card.id + ': unknown source ' + step.source);
    const credit = source
      ? `<a class="help-source" href="${escape(source.url)}">Source: ${escape(source.title)} ↗</a>`
      : `<span class="help-source own-advice">${OWN_ADVICE}</span>`;
    return `${pad}  <li>${escape(step.text)} ${credit}</li>`;
  });
  return [`${pad}<ol class="help-steps">`, ...items, `${pad}</ol>`];
}

function topic(card, help, pad) {
  const lines = [`${pad}<details id="${escape(card.id)}" class="help-topic-card">`,
    `${pad}  <summary>${escape(card.title)}</summary>`,
    `${pad}  <div class="detail-body">`];
  if (card.summary) lines.push(`${pad}    <p class="help-summary">${escape(card.summary)}</p>`);
  if (card.steps) lines.push(...steps(card, help, pad + '    '));
  if (card.children) {
    lines.push(`${pad}    <p class="help-choose">${escape(card.choose || 'Choose one.')}</p>`,
      `${pad}    <div class="payment-routes">`);
    for (const id of card.children) {
      const child = help.cards.find(c => c.id === id);
      if (!child) throw new Error(card.id + ': unknown child ' + id);
      lines.push(...topic(child, help, pad + '      '));
    }
    lines.push(`${pad}    </div>`);
  }
  lines.push(`${pad}  </div>`, `${pad}</details>`);
  return lines;
}

function block(help) {
  const pad = '          ';
  const lines = [pad + START];
  if (!help.approvedBy) lines.push(`${pad}<p id="help-draft" class="help-draft">Draft: these steps are waiting for a person to check them against their sources.</p>`);
  for (const card of help.cards.filter(c => !c.parent)) lines.push(...topic(card, help, pad));
  lines.push(pad + END);
  return lines.join('\n');
}

function render(page, help) {
  const a = page.indexOf(START), b = page.indexOf(END);
  if (a < 0 || b < a) throw new Error('recover.html is missing the help-cards markers');
  const lineStart = page.lastIndexOf('\n', a) + 1;
  return page.slice(0, lineStart) + block(help) + page.slice(b + END.length);
}

function main() {
  const page = fs.readFileSync(PAGE, 'utf8');
  const next = render(page, loadHelp());
  if (process.argv.includes('--check')) {
    if (next !== page) {
      console.error('recover.html does not match data/help-cards.js. Run: node scripts/build-recover.cjs');
      return 1;
    }
    console.log('Recovery page matches data/help-cards.js');
    return 0;
  }
  fs.writeFileSync(PAGE, next);
  console.log('Wrote the help topics in recover.html from data/help-cards.js');
  return 0;
}

if (require.main === module) process.exitCode = main();
module.exports = { render, loadHelp, block, START, END, OWN_ADVICE };
