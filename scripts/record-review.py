"""Record a completed human review of the five reviewed organizations.

Run this only AFTER the reviewer has opened every source URL listed in
docs/testing/five-organization-review.json and confirmed each value, its purpose, its
scope and the surrounding wording. Running it is the reviewer's statement that they did.

    python3 scripts/record-review.py --reviewer "Full Name" --date 2026-10-24

It writes the same reviewer, review date and 90-day due date into every file that
records the review, so they cannot disagree:

  data/store.js                                   contacts + sourceReview of the 5 orgs
  docs/testing/five-organization-review.json      the review record (ledger)
  docs/testing/five-organization-review.xlsx      columns K, L, N, O and the notes
  docs/testing/five-organization-test-results.json regenerated by the five-org test

Then it runs the review gate and the workbook checker. Uses only the Python standard
library. Safe to re-run: it overwrites the previous values rather than appending.
"""
import argparse
import datetime as dt
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import zipfile
from collections import OrderedDict
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
STORE = ROOT / "data/store.js"
LEDGER = ROOT / "docs/testing/five-organization-review.json"
WORKBOOK = ROOT / "docs/testing/five-organization-review.xlsx"
EXCEPTION_DATE = "October 24, 2026"
PLACEHOLDER = re.compile(r"REVIEWER(?:_\d+)?_NAME|REPLACE[_ ]?WITH|TODO|FIXME|^<.*>$", re.I)
JSON_STRING = r'"(?:[^"\\]|\\.)*"'


def fail(message):
    sys.exit("record-review: " + message)


def span(text, start, open_ch, close_ch):
    """Index just past the bracket that closes the one at text[start]."""
    depth, in_string, escaped = 0, False, False
    for i in range(start, len(text)):
        ch = text[i]
        if in_string:
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                in_string = False
        elif ch == '"':
            in_string = True
        elif ch == open_ch:
            depth += 1
        elif ch == close_ch:
            depth -= 1
            if depth == 0:
                return i + 1
    fail("unbalanced brackets in data/store.js")


def set_field(block, key, value, expected_count=None):
    pattern = re.compile(r'("%s": )%s' % (re.escape(key), JSON_STRING))
    block, count = pattern.subn(lambda m: m.group(1) + json.dumps(value, ensure_ascii=False), block)
    if expected_count is not None and count != expected_count:
        fail("expected %d %s field(s), found %d" % (expected_count, key, count))
    return block, count


def update_store(org_ids, reviewer, date, due):
    text = STORE.read_text(encoding="utf-8")
    total = 0
    for org_id in org_ids:
        marker = text.find('"id": "%s",' % org_id)
        if marker < 0:
            fail("organization %s not found in data/store.js" % org_id)
        start = text.rindex("{", 0, marker)
        end = span(text, start, "{", "}")
        org = text[start:end]

        c_key = org.find('"contacts": [')
        if c_key < 0:
            fail(org_id + " has no contacts array")
        c_start = org.index("[", c_key)
        c_end = span(org, c_start, "[", "]")
        contacts = org[c_start:c_end]
        n_reviewed = contacts.count('"status": "reviewed"')
        if n_reviewed == 0 or '"status": "draft"' in contacts:
            fail(org_id + ": every contact must already be status reviewed (apply the activation patch first)")
        contacts, _ = set_field(contacts, "reviewedBy", reviewer, n_reviewed)
        contacts, _ = set_field(contacts, "checkedOn", date, n_reviewed)
        contacts, _ = set_field(contacts, "reviewDue", due, n_reviewed)
        org = org[:c_start] + contacts + org[c_end:]
        total += n_reviewed

        s_key = org.find('"sourceReview": {')
        if s_key >= 0:
            s_start = org.index("{", s_key)
            s_end = span(org, s_start, "{", "}")
            review = org[s_start:s_end]
            review, _ = set_field(review, "reviewer", reviewer, 1)
            review, _ = set_field(review, "date", date, 1)
            review, _ = set_field(review, "reviewDue", due, 1)
            org = org[:s_start] + review + org[s_end:]
        text = text[:start] + org + text[end:]
    STORE.write_text(text, encoding="utf-8")
    return total


def update_ledger(reviewer, date, due):
    ledger = json.loads(LEDGER.read_text(encoding="utf-8"), object_pairs_hook=OrderedDict)
    ledger["reviewer"] = reviewer
    ledger["reviewDate"] = date
    ledger["reviewDue"] = due
    ledger["approvalStatus"] = "approved"
    LEDGER.write_text(json.dumps(ledger, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return ledger


def set_cell(xml, ref, inner_xml, cell_type):
    """Replace one <x:c r="REF" ...> cell, keeping its style index."""
    pattern = re.compile(r'<x:c r="%s"( s="\d+")?(?: t="[a-zA-Z]+")?\s*(?:/>|>.*?</x:c>)' % ref, re.S)
    match = pattern.search(xml)
    if not match:
        fail("workbook cell %s not found" % ref)
    style = match.group(1) or ""
    replacement = '<x:c r="%s"%s t="%s"><x:v>%s</x:v></x:c>' % (ref, style, cell_type, inner_xml)
    return xml[:match.start()] + replacement + xml[match.end():]


def cell_text(xml, ref):
    match = re.search(r'<x:c r="%s"[^>]*>\s*<x:v>(.*?)</x:v>' % ref, xml, re.S)
    return match.group(1) if match else ""


def update_workbook(ledger, reviewer, date, due):
    stamp = lambda day: day + "T00:00:00.000Z"
    expired = (dt.date.fromisoformat(due) + dt.timedelta(days=1)).isoformat()
    with zipfile.ZipFile(WORKBOOK) as archive:
        entries = [(info, archive.read(info.filename)) for info in archive.infolist()]
    parts = {info.filename: data for info, data in entries}
    summary = parts["xl/worksheets/sheet1.xml"].decode("utf-8")
    results = parts["xl/worksheets/sheet2.xml"].decode("utf-8")

    for row, org in enumerate(ledger["organizations"], 2):
        if cell_text(summary, "A%d" % row) != escape(org["name"]):
            fail("workbook row %d is not %s; refusing to write" % (row, org["name"]))
        summary = set_cell(summary, "K%d" % row, stamp(date), "d")
        summary = set_cell(summary, "L%d" % row, escape(reviewer), "str")
        summary = set_cell(summary, "N%d" % row, stamp(due), "d")
        summary = set_cell(summary, "O%d" % row, "Approved", "str")
    summary = set_cell(summary, "A12", escape(
        "Reviewer: one trained volunteer, named in column L, opened every source URL on the review "
        "date in column K. RELEASE.md records a dated single-reviewer exception (%s) to its "
        "two-volunteer rule, for these five organizations only. All 9 contacts are Approved." % EXCEPTION_DATE), "str")
    summary = set_cell(summary, "A13", escape(
        "Review date: %s, America/Los_Angeles. Review due: %s, 90 calendar days later. The due date "
        "is inclusive; %s is expired. Recheck on source changes and after expiry." % (date, due, expired)), "str")

    row = 2
    while re.search(r'<x:c r="G%d"' % row, results):
        results = set_cell(results, "G%d" % row, stamp(date), "d")
        row += 1

    parts["xl/worksheets/sheet1.xml"] = summary.encode("utf-8")
    parts["xl/worksheets/sheet2.xml"] = results.encode("utf-8")
    handle, temp = tempfile.mkstemp(dir=WORKBOOK.parent, suffix=".xlsx")
    os.close(handle)
    with zipfile.ZipFile(temp, "w") as out:
        for info, _ in entries:
            out.writestr(info, parts[info.filename], compress_type=info.compress_type)
    os.replace(temp, WORKBOOK)
    return row - 2


def run(label, command):
    print("\n== " + label + ": " + " ".join(command))
    done = subprocess.run(command, cwd=ROOT)
    if done.returncode:
        fail(label + " failed; fix the problem above and run this script again")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--reviewer", required=True, help="the reviewer's real full name")
    parser.add_argument("--date", required=True, help="the day the review was actually done, YYYY-MM-DD")
    args = parser.parse_args()

    reviewer = " ".join(args.reviewer.split())
    if len(reviewer) < 3 or PLACEHOLDER.search(reviewer):
        fail("give the reviewer's real name, not a template value")
    try:
        date = dt.date.fromisoformat(args.date)
    except ValueError:
        fail("--date must be a real date in YYYY-MM-DD form")
    if date > dt.date.today() + dt.timedelta(days=1):
        fail("--date is in the future; use the day the pages were actually checked")
    if date < dt.date(2026, 10, 17):
        fail("--date is before the five-organization scenarios' expiry fixture (2026-10-16); "
             "a review that old is not the one this record describes")
    due = (date + dt.timedelta(days=90)).isoformat()
    date = date.isoformat()

    ledger = json.loads(LEDGER.read_text(encoding="utf-8"))
    org_ids = [org["id"] for org in ledger["organizations"]]
    contacts = update_store(org_ids, reviewer, date, due)
    ledger = update_ledger(reviewer, date, due)
    rows = update_workbook(ledger, reviewer, date, due)
    print("Recorded: %s reviewed %d contacts across %d organizations on %s; due %s."
          % (reviewer, contacts, len(org_ids), date, due))
    print("Updated data/store.js, the review record, and the workbook (5 summary rows, %d result rows)." % rows)

    run("Regenerate the test report", ["node", "tests/five-org-review.cjs", "--write-report"])
    run("Review evidence gate", ["node", "tests/review-placeholders.cjs"])
    run("Workbook consistency", [sys.executable, "tests/review-artifact-consistency.py"])
    print("\nDone. Now run the full suite: npm test")


if __name__ == "__main__":
    main()
